"""Copy exact shipped operating extents into SGCC's exclusion sidecar.

This lexical reader extracts the existing schema-4 array fields without evaluating RON.
The runtime RON loader remains the authority on the generated document's validity.
"""
from pathlib import Path
import ast
import math
import hashlib
import re

PEERS = ("india_nepal_bhutan", "southern_china", "ips_ups")


def array_field(text, name):
    match = re.search(r"(?m)^\s*" + re.escape(name) + r"\s*:\s*\[", text)
    if match is None:
        return "[]"
    start = match.end() - 1
    depth, quoted, escaped, comment = 0, False, False, False
    for at in range(start, len(text)):
        char = text[at]
        if comment:
            if char == "\n":
                comment = False
            continue
        if not quoted and text[at : at + 2] == "//":
            comment = True
            continue
        if char == '"' and not escaped:
            quoted = not quoted
        if not quoted:
            if char == "[":
                depth += 1
            elif char == "]":
                depth -= 1
                if depth == 0:
                    return text[start : at + 1]
        escaped = char == "\\" and not escaped
    raise ValueError(f"unterminated {name} array")


def generate(root):
    regions = root / "assets" / "regions"
    header = [
        "// Generated by python3 -I tools/region_authoring/sgcc_exclusions.py",
        "// Preserve the shipped India, Southern China and IPS/UPS operating extents.",
    ]
    target = (regions / "sgcc.ron").read_text()
    def number(text, key):
        return float(re.search(r"\b" + key + r"\s*:\s*([-0-9.]+)", text).group(1))
    tw, te, ts, tn = (number(target, key) for key in ("west", "east", "south", "north"))
    width, height = (int(number(target, key)) for key in ("width", "height"))
    dx, dy = (te - tw) / width, (tn - ts) / height
    blocked = set()
    def polygons(source, field):
        return ast.literal_eval(re.sub(r"//[^\n]*", "", array_field(source, field)))
    def spans(rings, lat):
        result = []
        for ring in rings:
            intersections = []
            for (ax, ay), (bx, by) in zip(ring, ring[1:] + ring[:1]):
                if (ay > lat) != (by > lat):
                    intersections.append(ax + (lat - ay) * (bx - ax) / (by - ay))
            intersections.sort()
            result.extend(zip(intersections[::2], intersections[1::2]))
        return result

    for peer in PEERS:
        main = (regions / (peer + ".ron")).read_bytes()
        text = main.decode("utf-8")
        names = re.findall(r'"([^"\n]+)"', array_field(text, "geography"))
        if any(not re.fullmatch(r"[a-z0-9_]+\.ron", name) for name in names):
            raise ValueError("invalid sidecar name")
        sidecars = {name: (regions / peer / name).read_bytes() for name in names}
        bundle = main
        if sidecars:
            entries = [(peer + ".ron", main)] + [
                (peer + "/" + name, data) for name, data in sorted(sidecars.items())
            ]
            bundle = b"megawatt-region-bundle 1\n" + b"".join(
                f"{name} {len(data)}\n".encode() + data for name, data in entries
            )
        header.append(f"// {peer} canonical bundle SHA-256 {hashlib.sha256(bundle).hexdigest()}")
        land, exclude = [], []
        for source in [*sidecars.values(), main]:
            decoded = source.decode("utf-8")
            land.extend(polygons(decoded, "land"))
            exclude.extend(polygons(decoded, "exclude"))
        pw, pe, ps, pn = (number(text, key) for key in ("west", "east", "south", "north"))
        nx, ny = (int(number(text, key)) for key in ("width", "height"))
        px, py = (pe - pw) / nx, (pn - ps) / ny
        for y in range(ny):
            top, bottom = pn - y * py, pn - (y + 1) * py
            if top <= ts or bottom >= tn:
                continue
            lat = (top + bottom) / 2
            inside, outside = spans(land, lat), spans(exclude, lat)
            for x in range(nx):
                west, east = pw + x * px, pw + (x + 1) * px
                if east <= tw or west >= te:
                    continue
                lon = (west + east) / 2
                if not any(a < lon < b for a, b in inside) or any(a < lon < b for a, b in outside):
                    continue
                # Exclude every SGCC cell intersecting a peer land cell. Point-only
                # exclusion is insufficient where the two raster resolutions differ.
                for gy in range(max(0, math.floor((tn - top) / dy)), min(height, math.ceil((tn - bottom) / dy))):
                    for gx in range(max(0, math.floor((west - tw) / dx)), min(width, math.ceil((east - tw) / dx))):
                        blocked.add((gx, gy))
    rings = []
    for y in range(height):
        xs = sorted(x for x, row in blocked if row == y)
        while xs:
            first = last = xs.pop(0)
            while xs and xs[0] == last + 1:
                last = xs.pop(0)
            west, east, top, bottom = tw + first * dx, tw + (last + 1) * dx, tn - y * dy, tn - (y + 1) * dy
            rings.append(f"    [({west:.9f},{bottom:.9f}),({east:.9f},{bottom:.9f}),({east:.9f},{top:.9f}),({west:.9f},{top:.9f})]")
    header.append("// Cell-aligned seam: SGCC cells intersecting existing peer land cells are excluded.")
    return "\n".join(header) + "\n(land: [], exclude: [\n" + ",\n".join(rings) + "\n])\n"



if __name__ == "__main__":
    print(generate(Path(__file__).resolve().parents[2]), end="")
